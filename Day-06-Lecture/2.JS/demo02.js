// Variable Declaration and Initialization
let num; // Declaration
num = 42; // Initialization

console.log("The number is " + num);

const PI = 3.14 //Declaration and Initialization
console.log("The value of PI is " + PI);

//Mutable and Immutable Variables
num = 100; // Reassigning mutable variable
console.log("The updated number is " + num);

PI = 3.14159; // This will cause an error as PI is immutable
console.log("The updated value of PI is " + PI);